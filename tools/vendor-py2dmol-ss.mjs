/**
 * Vendor py2Dmol's Cα-only secondary-structure assignment (`assignSecondary`: backbone predicted from the Cα trace,
 * then DSSP hydrogen-bond rules on it) as a standalone ES module.
 *
 *   node tools/vendor-py2dmol-ss.mjs [../py2Dmol]
 *
 * `src/cartoon/geom.js` is a 12k-line classic script that also holds the renderer, so this copies only the top-level
 * declarations `assignSecondary` reaches (traced by identifier), verbatim and in source order, into
 * `web/vendor/py2dmol-ss.js`. Re-run after updating ../py2Dmol; the header records the source commit.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_REPO = resolve(process.argv[2] ?? join(ROOT, '../py2Dmol'));
const SRC = join(SRC_REPO, 'src/cartoon/geom.js');
const OUT = join(ROOT, 'web/vendor/py2dmol-ss.js');
const ENTRY = ['assignSecondary'];

const text = readFileSync(SRC, 'utf8');
const lines = text.split('\n');
// Top-level declarations start at column 0; each block runs to the next one (its leading comment included).
const declRe = /^(?:async\s+)?(?:function\*?\s+([A-Za-z_$][\w$]*)|(?:const|let|var)\s+([A-Za-z_$][\w$]*))/;
const starts = [];
for (let i = 0; i < lines.length; i += 1) {
  const m = declRe.exec(lines[i]);
  if (m) starts.push({ line: i, name: m[1] ?? m[2] });
}
const blocks = starts.map((s, k) => {
  // Pull the preceding comment block in with the declaration.
  let begin = s.line;
  while (begin > 0 && /^\s*(\/\/|\/\*|\*|\*\/)/.test(lines[begin - 1])) begin -= 1;
  const end = k + 1 < starts.length ? starts[k + 1].line : lines.length;
  return { name: s.name, begin, decl: s.line, end };
});
for (let k = 0; k + 1 < blocks.length; k += 1) blocks[k].end = Math.min(blocks[k].end, blocks[k + 1].begin);
const byName = new Map(blocks.map((b) => [b.name, b]));
const code = (b) => lines.slice(b.decl, b.end).join('\n').replace(/\/\*[\s\S]*?\*\/|\/\/.*$/gm, '');

const keep = new Set();
const queue = [...ENTRY];
while (queue.length) {
  const name = queue.pop();
  if (keep.has(name)) continue;
  const b = byName.get(name);
  if (!b) throw new Error(`${name}: no top-level declaration in ${SRC}`);
  keep.add(name);
  for (const id of new Set(code(b).match(/[A-Za-z_$][\w$]*/g))) {
    if (id !== name && byName.has(id) && !keep.has(id)) queue.push(id);
  }
}

const commit = execFileSync('git', ['-C', SRC_REPO, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const body = blocks.filter((b) => keep.has(b.name)).map((b) => lines.slice(b.begin, b.end).join('\n').trimEnd());
const out = `// GENERATED by tools/vendor-py2dmol-ss.mjs from py2Dmol src/cartoon/geom.js @ ${commit}. Do not edit.
// Cα-only secondary structure: backbone predicted from the Cα trace, then DSSP hydrogen-bond rules.
/* eslint-disable */

${body.join('\n\n')}

export { ${ENTRY.join(', ')} };
`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);
console.log(`${OUT}: ${keep.size} declarations, ${out.split('\n').length} lines (py2Dmol ${commit.slice(0, 7)})`);
console.log([...keep].join(' '));
