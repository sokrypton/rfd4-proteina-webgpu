/**
 * Copy LocalFold's refold code into this repository at the commit `localfold.json` pins.
 *
 * Reads files with `git show <commit>:<path>` from a LocalFold checkout (`../localfold`, or `LOCALFOLD_DIR`), so the
 * copy is exactly that commit whatever the checkout has in its working tree. Starting from `entries`, it follows every
 * relative `import` / `export ... from` / `import("...")` and copies the closure, keeping LocalFold's own layout, into
 * `vendor/localfold-<commit>/`. The commit in the directory name is the cache-busting: a re-sync is a new path, so a
 * browser can never mix two versions. Older `vendor/localfold-*` directories are removed. `web/localfold.js` is
 * rewritten to re-export the entries from the new directory.
 *
 *     node tools/sync-localfold.mjs            # copy the pinned commit
 *     node tools/sync-localfold.mjs <commit>   # pin a new commit, then copy it
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const PIN = join(ROOT, "localfold.json");
const SOURCE = resolve(process.env.LOCALFOLD_DIR ?? join(ROOT, "..", "localfold"));

const pin = JSON.parse(readFileSync(PIN, "utf8"));
const git = (...args) => execFileSync("git", ["-C", SOURCE, ...args], { encoding: "utf8", maxBuffer: 64 << 20 });

if (process.argv[2]) {
  pin.commit = git("rev-parse", "--short=8", `${process.argv[2]}^{commit}`).trim();
  writeFileSync(PIN, `${JSON.stringify(pin, null, 2)}\n`);
}
const commit = git("rev-parse", "--short=8", `${pin.commit}^{commit}`).trim();

// Relative specifiers only: LocalFold's browser code has no bare imports, and one appearing is worth stopping on.
const IMPORT = /(?:import|export)\s[^;]*?from\s*["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)|import\s*["']([^"']+)["']/g;
const files = new Map();
const pending = [...pin.entries];
while (pending.length) {
  const path = pending.pop();
  if (files.has(path)) continue;
  const text = git("show", `${commit}:${path}`);
  files.set(path, text);
  for (const match of text.matchAll(IMPORT)) {
    const spec = match[1] ?? match[2] ?? match[3];
    // `import("./x.js")` inside a JSDoc type is a type, not a load; it still names a real file, so copying it is harmless.
    if (!spec.startsWith(".")) throw new Error(`${path} imports '${spec}', which is not relative`);
    pending.push(posix.normalize(posix.join(posix.dirname(path), spec)));
  }
}
files.set("LICENSE", git("show", `${commit}:LICENSE`));

const vendorRoot = join(ROOT, "vendor");
const outDir = join(vendorRoot, `localfold-${commit}`);
mkdirSync(vendorRoot, { recursive: true });
for (const name of readdirSync(vendorRoot)) {
  if (name.startsWith("localfold-")) rmSync(join(vendorRoot, name), { recursive: true, force: true });
}
for (const [path, text] of files) {
  mkdirSync(dirname(join(outDir, path)), { recursive: true });
  writeFileSync(join(outDir, path), text);
}

const shim = [
  `// Generated by tools/sync-localfold.mjs from ${pin.repository} at ${commit}. Do not edit; re-run the tool.`,
  ...pin.entries.map((entry) => `export * from '../vendor/localfold-${commit}/${entry}';`),
  "",
].join("\n");
writeFileSync(join(ROOT, "web", "localfold.js"), shim);

const lines = [...files.values()].reduce((sum, text) => sum + text.split("\n").length, 0);
console.log(`localfold ${commit}: ${files.size} files, ${lines} lines -> vendor/localfold-${commit}/`);
